CREATE OR REPLACE FUNCTION guard_inventory() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended(NEW.room_id,0));
 IF TG_TABLE_NAME='bookings' THEN
 IF NEW.status NOT IN ('PENDING','CONFIRMED','PAID','CHECKED-IN') THEN RETURN NEW; END IF;
 IF EXISTS(SELECT 1 FROM availability_blocks WHERE room_id=NEW.room_id AND checkin<NEW.checkout AND checkout>NEW.checkin) THEN RAISE EXCEPTION 'blocked date conflict'; END IF;
 ELSIF TG_TABLE_NAME='availability_blocks' THEN
 IF EXISTS(SELECT 1 FROM bookings WHERE room_id=NEW.room_id AND status IN ('PENDING','CONFIRMED','PAID','CHECKED-IN') AND checkin<NEW.checkout AND checkout>NEW.checkin) THEN RAISE EXCEPTION 'booking conflict'; END IF;
 END IF; RETURN NEW; END $$;
CREATE TRIGGER bookings_guard BEFORE INSERT OR UPDATE ON bookings FOR EACH ROW EXECUTE FUNCTION guard_inventory();
CREATE TRIGGER blocks_guard BEFORE INSERT OR UPDATE ON availability_blocks FOR EACH ROW EXECUTE FUNCTION guard_inventory();
CREATE OR REPLACE FUNCTION create_reservation(reservation jsonb,guest_record jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$ DECLARE t text:=now()::text; BEGIN
 INSERT INTO guests(id,email,data,created_at,updated_at) VALUES(guest_record->>'id',guest_record->>'email',guest_record,t,t) ON CONFLICT(id) DO NOTHING;
 INSERT INTO bookings(id,room_id,guest_id,checkin,checkout,status,source,idempotency_key,data,created_at,updated_at) VALUES(reservation->>'id',reservation->>'room_id',guest_record->>'id',reservation->>'checkin',reservation->>'checkout',reservation->>'status',reservation->>'source',reservation->>'idempotency_key',reservation,t,t);
 INSERT INTO booking_guests(id,booking_id,guest_id,data,created_at,updated_at) VALUES(gen_random_uuid()::text,reservation->>'id',guest_record->>'id','{}',t,t);
 INSERT INTO audit_logs(id,data,created_at,updated_at) VALUES(gen_random_uuid()::text,jsonb_build_object('action','booking.created','booking_id',reservation->>'id'),t,t);
 RETURN reservation; END $$;
CREATE OR REPLACE FUNCTION take_rate_limit(key_id text,max_count int) RETURNS boolean LANGUAGE plpgsql AS $$ DECLARE count_value int; BEGIN
 INSERT INTO rate_limits(id,data,created_at,updated_at) VALUES(key_id,'{"count":1}',now()::text,now()::text) ON CONFLICT(id) DO UPDATE SET data=jsonb_build_object('count',(rate_limits.data->>'count')::int+1) RETURNING (data->>'count')::int INTO count_value;
 RETURN count_value<=max_count; END $$;
CREATE OR REPLACE FUNCTION replace_channel_blocks(integration text,blocks jsonb) RETURNS void LANGUAGE plpgsql AS $$ DECLARE b jsonb; BEGIN
 DELETE FROM availability_blocks WHERE integration_id=integration;
 FOR b IN SELECT * FROM jsonb_array_elements(blocks) LOOP
 INSERT INTO availability_blocks(id,room_id,checkin,checkout,source,external_uid,integration_id,data,created_at,updated_at) VALUES(b->>'id',b->>'room_id',b->>'checkin',b->>'checkout',b->>'source',b->>'external_uid',integration,b,now()::text,now()::text);
 END LOOP; END $$;
REVOKE ALL ON FUNCTION create_reservation(jsonb,jsonb),take_rate_limit(text,int),replace_channel_blocks(text,jsonb) FROM PUBLIC;
