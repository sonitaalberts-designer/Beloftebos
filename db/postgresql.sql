CREATE OR REPLACE FUNCTION save_function(function_record jsonb,room_ids text[]) RETURNS jsonb LANGUAGE plpgsql AS $$ DECLARE t text:=now()::text; r text; BEGIN
 DELETE FROM availability_blocks WHERE function_id=function_record->>'id';
 INSERT INTO functions(id,checkin,checkout,status,data,created_at,updated_at) VALUES(function_record->>'id',function_record->>'checkin',function_record->>'checkout',function_record->>'status',function_record,t,t) ON CONFLICT(id) DO UPDATE SET checkin=excluded.checkin,checkout=excluded.checkout,status=excluded.status,data=excluded.data,updated_at=excluded.updated_at;
 IF function_record->>'status'='CONFIRMED' THEN FOREACH r IN ARRAY room_ids LOOP
 INSERT INTO availability_blocks(id,room_id,checkin,checkout,source,function_id,data,created_at,updated_at) VALUES(gen_random_uuid()::text,r,function_record->>'checkin',function_record->>'checkout','FUNCTION',function_record->>'id',jsonb_build_object('notes',function_record->>'name'),t,t);
 END LOOP; END IF;
 INSERT INTO audit_logs(id,data,created_at,updated_at) VALUES(gen_random_uuid()::text,jsonb_build_object('action','function.saved','function_id',function_record->>'id'),t,t);
 RETURN function_record; END $$;
REVOKE ALL ON FUNCTION save_function(jsonb,text[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION save_function(jsonb,text[]) TO service_role;
